<x-legal-layout title="Cancellation & Refund Policy">
    <p>This Cancellation &amp; Refund Policy explains how cancellations, changes and refunds are handled for bookings made through Travelera.</p>
    <p>Travelera is a travel service brand operated by <strong>TRAVEL ERA LLC</strong>.</p>
    <p>Because Travelera facilitates travel bookings involving airlines and other travel suppliers, refund and cancellation eligibility may depend on the applicable fare rules, supplier policies and applicable law.</p>

    <h2>1. General Cancellation and Refund Principles</h2>
    <p>Cancellation and refund eligibility depends on:</p>
    <ul>
        <li>The airline or supplier;</li>
        <li>The type of ticket or service purchased;</li>
        <li>Whether the fare is refundable or non-refundable;</li>
        <li>The applicable fare rules;</li>
        <li>When the cancellation request is made;</li>
        <li>Whether the ticket has been partially or fully used;</li>
        <li>Whether the airline has cancelled or significantly changed the itinerary; and</li>
        <li>Applicable law.</li>
    </ul>
    <p>Customers should contact Travelera as soon as possible when they wish to cancel or change a booking.</p>

    <h2>2. Customer-Requested Cancellation</h2>
    <p>If a customer voluntarily requests cancellation of a booking, Travelera will review the applicable airline or supplier rules.</p>
    <p>Depending on the booking, the customer may be responsible for:</p>
    <ul>
        <li>Airline cancellation fees;</li>
        <li>Supplier penalties;</li>
        <li>Fare restrictions;</li>
        <li>Applicable Travelera service or processing fees, if disclosed and applicable; and</li>
        <li>Other applicable charges.</li>
    </ul>
    <p>Before processing an eligible cancellation, Travelera will provide the customer with the applicable refund information when reasonably available.</p>

    <h2>3. Non-Refundable Tickets</h2>
    <p>A ticket identified as non-refundable is generally not eligible for a voluntary refund when the flight operates as scheduled and the customer chooses not to travel.</p>
    <p>However, exceptions may apply under:</p>
    <ul>
        <li>Airline fare rules;</li>
        <li>Applicable law;</li>
        <li>Airline cancellation;</li>
        <li>Qualifying significant schedule changes; or</li>
        <li>Other circumstances in which a refund is legally required.</li>
    </ul>

    <h2>4. Refundable Tickets</h2>
    <p>Refundable tickets may be eligible for a refund in accordance with the applicable fare rules and applicable law.</p>
    <p>Any applicable Travelera service fee or other disclosed charge will be handled according to the terms presented to the customer at the time of booking or service.</p>

    <h2>5. Airline Cancellation</h2>
    <p>If an airline cancels a flight, customers may be entitled to a refund when they do not accept alternative transportation, travel credits, vouchers or other compensation offered in lieu of a refund, subject to applicable law.</p>
    <p>For applicable U.S. air transportation, DOT rules provide refund rights when an airline cancels or significantly changes a flight and the passenger does not accept the alternative. (Department of Transportation)</p>
    <p>If Travelera is the merchant of record for the ticket transaction, applicable DOT rules may make Travelera responsible for issuing a qualifying airfare refund. (Department of Transportation)</p>

    <h2>6. Significant Schedule Changes</h2>
    <p>Certain significant airline schedule changes may provide a customer with refund rights under applicable law if the customer does not accept the changed itinerary or alternative transportation.</p>
    <p>For applicable U.S. air transportation, DOT identifies significant changes including certain early departures of 3 or more hours for domestic itineraries or 6 or more hours for international itineraries, changes to origin or destination airports, increases in connections, and certain class-of-service downgrades. (Department of Transportation)</p>
    <p>Specific refund eligibility depends on the applicable law and the circumstances of the itinerary.</p>

    <h2>7. Airline Rebooking</h2>
    <p>When an airline cancels or significantly changes a flight, the airline may offer alternative transportation.</p>
    <p>Customers may be offered options such as:</p>
    <ul>
        <li>Rebooking on another flight;</li>
        <li>An alternative itinerary;</li>
        <li>Travel credit or voucher, where permitted; or</li>
        <li>A refund where applicable.</li>
    </ul>
    <p>If a customer accepts alternative transportation or other compensation instead of a refund, the applicable terms of that accepted option will apply.</p>

    <h2>8. 24-Hour Cancellation</h2>
    <p>The federal 24-hour reservation requirement applies to qualifying airline reservations made at least seven days before scheduled departure. However, DOT states that this requirement does not apply to tickets booked through online travel agencies, travel agents or other third-party agents in the same manner as direct airline purchases. (Department of Transportation)</p>
    <p>Travelera will therefore handle 24-hour cancellation requests according to the applicable booking terms, airline/supplier policy and applicable law.</p>
    <p>Where a specific airline or supplier provides a 24-hour cancellation or refund option for a booking made through Travelera, that option will be handled according to the applicable terms.</p>

    <h2>9. Changes to Bookings</h2>
    <p>Customers requesting changes may be responsible for:</p>
    <ul>
        <li>Airline change fees;</li>
        <li>Fare differences;</li>
        <li>Taxes and other applicable charges;</li>
        <li>Supplier fees; and</li>
        <li>Any applicable Travelera service fee disclosed for the requested service.</li>
    </ul>
    <p>Changes are subject to availability and the applicable airline or supplier rules.</p>

    <h2>10. No-Show Bookings</h2>
    <p>If a passenger does not travel and does not cancel or change the reservation within the applicable period, the booking may be treated as a no-show.</p>
    <p>No-show consequences vary by airline and fare type and may result in:</p>
    <ul>
        <li>Loss of ticket value;</li>
        <li>Cancellation of remaining itinerary segments;</li>
        <li>Additional charges; or</li>
        <li>Limited or no refund eligibility.</li>
    </ul>
    <p>Customers should contact Travelera before scheduled departure if they will not be travelling.</p>

    <h2>11. Partially Used Tickets</h2>
    <p>Refunds for partially used tickets are subject to the applicable airline fare rules.</p>
    <p>The amount already used, applicable fare calculation, cancellation restrictions and other charges may affect the amount available for refund.</p>

    <h2>12. Refund Processing</h2>
    <p>When a refund is approved or otherwise required by applicable law, Travelera will process the refund according to the applicable airline/supplier process and applicable law.</p>
    <p>Refunds will generally be returned to the original form of payment, subject to applicable law, payment-provider rules and the circumstances of the transaction.</p>
    <p>For qualifying U.S. airline refunds, DOT generally requires prompt refunds, including within 7 business days for credit-card payments and 20 calendar days for other payment methods, once the refund becomes due. (Department of Transportation)</p>
    <p>Actual posting time to a customer’s bank or card account may depend on the customer’s financial institution or payment provider.</p>

